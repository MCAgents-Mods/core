package io.github.mcagentsmods.core.api.hologram;

/** The colour a line of a {@link Form} is drawn in. */
public enum FormTone {

    /** The panel's ordinary text. */
    TEXT,

    /** Lighter: a hint, a path, an explanation. */
    SOFT,

    /** Green: something worked or is on. */
    GOOD,

    /** Red: something failed or was refused. */
    BAD,

    /** Amber: a warning to read before going on. */
    WARN
}
